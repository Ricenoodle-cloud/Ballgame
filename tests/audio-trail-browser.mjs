import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
await mkdir('work',{recursive:true});
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox','--enable-unsafe-swiftshader'],headless:true});
try {
 const page=await browser.newPage({viewport:{width:1280,height:900}}),errors=[];
 page.setDefaultTimeout(60000);
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 await page.goto(process.env.GAME_URL||'http://localhost:5174');
 await page.waitForTimeout(700);
 assert.equal(await page.evaluate(()=>__orbitAudio.inspect().state),'locked');
 await page.screenshot({path:'work/v3-menu.png'});
 await page.getByRole('button',{name:'音频设置',exact:true}).click();
 await page.waitForFunction(()=>__orbitAudio.inspect().state==='running'&&__orbitAudio.inspect().rms>0.00001);
 console.log('PASS music unlocks on gesture, real audio graph produces signal');
 await page.getByLabel('背景音乐开关').uncheck();
 await page.waitForTimeout(3200);
 assert.equal(await page.evaluate(()=>__orbitAudio.inspect().activeMusicSources),0);
 assert.ok(await page.evaluate(()=>__orbitAudio.inspect().rms<.00001));
 await page.getByLabel('音效开关',{exact:true}).uncheck();
 await page.evaluate(()=>__orbitAudio.play('score'));
 await page.waitForTimeout(150);assert.ok(await page.evaluate(()=>__orbitAudio.inspect().rms<.00001));
 await page.getByLabel('音效开关',{exact:true}).check();
 await page.evaluate(()=>__orbitAudio.play('score'));
 await page.waitForFunction(()=>__orbitAudio.inspect().rms>.0001);
 console.log('PASS independent music/SFX switches control actual output');
 await page.getByLabel('背景音乐音量').fill('0.2');
 await page.getByLabel('音效音量',{exact:true}).fill('0.25');
 await page.reload();
 assert.equal(await page.evaluate(()=>__orbitAudio.settings.musicEnabled),false);
 assert.equal(await page.evaluate(()=>__orbitAudio.settings.musicVolume),.2);
 assert.equal(await page.evaluate(()=>__orbitAudio.settings.sfxVolume),.25);
 console.log('PASS audio settings persist across reload');
 await page.getByRole('button',{name:'音频设置',exact:true}).click();
 await page.getByLabel('背景音乐开关').check();
 await page.getByRole('button',{name:'音频设置',exact:true}).click();
 await page.getByRole('button',{name:'开始游戏',exact:true}).click();
 await page.waitForFunction(()=>__orbitBodies?.session===__orbitGame.getState().session && __orbitBodies?.player);
 // Keep targets safely out of the movement lane for deterministic trail inspection.
 await page.evaluate(()=>{for(const b of __orbitBodies.targets.values()){b.setBodyType(1,true);b.setTranslation({x:0,y:100,z:-20},true);}__orbitBodies.player.setTranslation({x:-4,y:.5,z:0},true);});
 await page.keyboard.down('d');
 await page.waitForFunction(()=>__orbitTrail?.count>=3&&__orbitTrail.length>.1);
 const normal=await page.evaluate(()=>__orbitTrail.length);
 await page.keyboard.press('Shift');
 await page.waitForFunction(()=>__orbitTrail.dash>.4&&__orbitTrail.length>.2);
 await page.keyboard.up('d');
 await page.screenshot({path:'work/v3-gold-trail.png'});
 assert.ok(await page.evaluate(()=>__orbitTrail.count<=64));
 console.log('PASS gold ribbon records physics path, sprint enhances trail, cache bounded',normal);
 await page.evaluate(()=>__orbitGame.getState().pause());
 await page.waitForFunction(()=>__orbitTrail.count===0);
 await page.evaluate(()=>__orbitGame.getState().start(1));
 await page.waitForTimeout(500);await page.screenshot({path:'work/v3-game.png'});
 // Return to menu: audio continues while the full original score crosses its loop.
 await page.evaluate(()=>__orbitGame.getState().menu());
 await page.waitForFunction(()=>__orbitAudio.inspect().step>258,null,{timeout:145000});
 assert.ok(await page.evaluate(()=>__orbitAudio.inspect().rms>.000001));
 console.log('PASS original 32-bar BGM crosses full loop boundary with live output');
 assert.deepEqual(errors,[]);console.log('PASS no page or shader runtime errors');
} finally {await browser.close();}
