import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
await mkdir('work', {recursive:true});
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader']});
const context=await browser.newContext({offline:true,viewport:{width:1024,height:768}});
const page=await context.newPage();
const errors=[],network=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(/^https?:/.test(r.url()))network.push(r.url());});
await page.setContent(await readFile('dist-offline/推小球闯关-V2-离线版.html','utf8'));
await page.getByRole('button',{name:'开始游戏'}).click();
await page.waitForTimeout(4000);
assert.equal(await page.locator('.scene-error').count(),0);
assert.equal(await page.locator('canvas').count(),1);
assert.ok(await page.locator('.scoreboard').isVisible());
await page.keyboard.down('w');await page.waitForTimeout(500);await page.keyboard.press('Shift');await page.keyboard.up('w');
await page.waitForTimeout(500);
await page.screenshot({path:'work/v2-offline.png'});
assert.deepEqual(network,[]);assert.deepEqual(errors,[]);
console.log('PASS complete HTML loads in offline browser via setContent, controls run, no HTTP requests or runtime errors; file:// blocked by browser administrator policy');
await browser.close();
